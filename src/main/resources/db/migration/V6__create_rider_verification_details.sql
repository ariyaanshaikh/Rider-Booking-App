CREATE TABLE IF NOT EXISTS RIDER_VERIFICATION_DETAILS (
    RIDER_ID BIGINT PRIMARY KEY REFERENCES RIDER_DETAILS(ID) ON DELETE CASCADE,
    AADHAAR_CARD_NUMBER VARCHAR(32) NOT NULL,
    PAN_CARD_NUMBER VARCHAR(16) NOT NULL,
    DRIVING_LICENSE_NUMBER VARCHAR(32) NOT NULL,
    BANK_ACCOUNT_NUMBER VARCHAR(64) NOT NULL,
    BANK_IFSC_CODE VARCHAR(16) NOT NULL,
    BANK_ACCOUNT_NAME VARCHAR(128) NOT NULL,
    IS_VERIFIED BOOLEAN NOT NULL DEFAULT FALSE
);
