CREATE TABLE IF NOT EXISTS USERS (
    ID BIGSERIAL PRIMARY KEY,
    FIRST_NAME VARCHAR(255), LAST_NAME VARCHAR(255), USER_NAME VARCHAR(255),
    PASSWORD VARCHAR(255), EMAIL VARCHAR(255), ENABLED BOOLEAN NOT NULL DEFAULT FALSE,
    TOKEN VARCHAR(255), CREATED_AT TIMESTAMP, EXPIRES_AT TIMESTAMP,
    CONFIRMED_AT TIMESTAMP, MOBILE_NUMBER VARCHAR(50), MOBILE_OTP VARCHAR(32),
    ROLE VARCHAR(16) NOT NULL,
    CONSTRAINT ck_users_role CHECK (ROLE IN ('ADMIN', 'RIDER'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_user_name ON USERS(USER_NAME);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email ON USERS(EMAIL);
-- Legacy Token is a separate entity, never another mapping of the USERS row.
CREATE TABLE IF NOT EXISTS confirmation_tokens (
    id BIGSERIAL PRIMARY KEY, token VARCHAR(255), created_at TIMESTAMP,
    expires_at TIMESTAMP, confirmed_at TIMESTAMP, user_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS RIDER_DETAILS (
    ID BIGSERIAL PRIMARY KEY,
    NAME VARCHAR(255), MOBILE_NUMBER VARCHAR(50),
    USER_ID BIGINT UNIQUE REFERENCES USERS(ID),
    STATUS VARCHAR(32) NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT ck_rider_status CHECK (STATUS IN ('AVAILABLE', 'ON_TRIP', 'OFFLINE'))
);
CREATE INDEX IF NOT EXISTS idx_rider_details_status ON RIDER_DETAILS(STATUS);

-- One private verification/bank-details record per rider. RIDER_ID is both
-- the primary key and a foreign key, so a second record for the same rider
-- cannot be created.
CREATE TABLE IF NOT EXISTS RIDER_VERIFICATION_DETAILS (
    RIDER_ID BIGINT PRIMARY KEY REFERENCES RIDER_DETAILS(ID) ON DELETE CASCADE,
    AADHAAR_CARD_NUMBER VARCHAR(32) NOT NULL,
    PAN_CARD_NUMBER VARCHAR(16) NOT NULL,
    DRIVING_LICENSE_NUMBER VARCHAR(32) NOT NULL,
    BANK_ACCOUNT_NUMBER VARCHAR(64) NOT NULL,
    BANK_IFSC_CODE VARCHAR(16) NOT NULL,
    BANK_ACCOUNT_NAME VARCHAR(128) NOT NULL,
    IS_VERIFIED BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_rider_verification_verified
    ON RIDER_VERIFICATION_DETAILS(IS_VERIFIED);

CREATE TABLE IF NOT EXISTS RIDE_DETAILS (
    RIDE_ID SERIAL PRIMARY KEY,
    PICKUP_LATITUDE DOUBLE PRECISION NOT NULL,
    PICKUP_LONGITUDE DOUBLE PRECISION NOT NULL,
    DROP_LATITUDE DOUBLE PRECISION NOT NULL,
    DROP_LONGITUDE DOUBLE PRECISION NOT NULL,
    FARE NUMERIC(10,2) NOT NULL CHECK (FARE > 0),
    CHASSIS_NO VARCHAR(100) NOT NULL,
    VEHICLE_NAME VARCHAR(150) NOT NULL,
    RIDER_ID INTEGER NOT NULL DEFAULT 0,
    ADMIN_ID INTEGER NOT NULL,
    RIDE_OTP BIGINT NOT NULL,
    RIDE_STATUS VARCHAR(32) NOT NULL DEFAULT 'REQUESTED',
    CONSTRAINT ck_ride_status CHECK (RIDE_STATUS IN
        ('REQUESTED', 'ACCEPTED', 'STARTED', 'COMPLETED', 'RIDER_CANCELLED', 'ADMIN_CANCELLED'))
);
CREATE INDEX IF NOT EXISTS idx_ride_details_status ON RIDE_DETAILS(RIDE_STATUS);
CREATE INDEX IF NOT EXISTS idx_ride_details_admin_id ON RIDE_DETAILS(ADMIN_ID);
CREATE INDEX IF NOT EXISTS idx_ride_details_rider_id ON RIDE_DETAILS(RIDER_ID);

CREATE TABLE IF NOT EXISTS RIDER_LOCATION (
    RIDER_ID INTEGER PRIMARY KEY REFERENCES RIDER_DETAILS(ID) ON DELETE CASCADE,
    CURRENT_LATITUDE DOUBLE PRECISION NOT NULL,
    CURRENT_LONGITUDE DOUBLE PRECISION NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Supports fresh-location filtering before precise Haversine calculation.
CREATE INDEX IF NOT EXISTS idx_rider_location_updated_at ON RIDER_LOCATION(UPDATED_AT DESC);

CREATE TABLE IF NOT EXISTS RIDE_REQUEST (
    ID SERIAL PRIMARY KEY,
    RIDE_ID INTEGER NOT NULL REFERENCES RIDE_DETAILS(RIDE_ID) ON DELETE CASCADE,
    RIDER_ID INTEGER NOT NULL REFERENCES RIDER_DETAILS(ID),
    STATUS VARCHAR(32) NOT NULL DEFAULT 'SENT',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ride_request_status CHECK (STATUS IN ('SENT', 'ACCEPTED', 'CANCELLED')),
    CONSTRAINT uq_ride_request_ride_rider UNIQUE (RIDE_ID, RIDER_ID)
);
CREATE INDEX IF NOT EXISTS idx_ride_request_ride_id ON RIDE_REQUEST(RIDE_ID);
CREATE INDEX IF NOT EXISTS idx_ride_request_rider_id ON RIDE_REQUEST(RIDER_ID);
CREATE INDEX IF NOT EXISTS idx_ride_request_status ON RIDE_REQUEST(STATUS);

CREATE TABLE IF NOT EXISTS INVOICES (
    INVOICE_ID SERIAL PRIMARY KEY,
    RIDE_ID INTEGER NOT NULL UNIQUE REFERENCES RIDE_DETAILS(RIDE_ID) ON DELETE CASCADE,
    RIDER_ID INTEGER NOT NULL REFERENCES RIDER_DETAILS(ID),
    USER_ID INTEGER NOT NULL REFERENCES USERS(ID),
    AMOUNT NUMERIC(10,2) NOT NULL CHECK (AMOUNT >= 0),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT ck_invoice_status CHECK (STATUS IN ('PENDING', 'SETTLED', 'REFUNDED'))
);
CREATE INDEX IF NOT EXISTS idx_invoices_rider_id ON INVOICES(RIDER_ID);
CREATE INDEX IF NOT EXISTS idx_invoices_user_id ON INVOICES(USER_ID);
CREATE INDEX IF NOT EXISTS idx_invoices_status ON INVOICES(STATUS);
CREATE INDEX IF NOT EXISTS idx_invoices_created_at ON INVOICES(CREATED_AT);

-- Additive migration: existing rides are not repriced or marked paid.
ALTER TABLE ride_details ADD COLUMN IF NOT EXISTS distance_meters BIGINT;
ALTER TABLE ride_details ADD COLUMN IF NOT EXISTS payment_completed VARCHAR(32);
ALTER TABLE ride_details ADD COLUMN IF NOT EXISTS payment_json JSONB;
ALTER TABLE ride_details ALTER COLUMN payment_json TYPE JSONB USING payment_json::jsonb;
ALTER TABLE ride_details DROP CONSTRAINT IF EXISTS ck_ride_status;
ALTER TABLE ride_details ADD CONSTRAINT ck_ride_status CHECK
    (ride_status IN ('REQUESTED','ACCEPTED','AWAITING_PAYMENT','STARTED','COMPLETED','RIDER_CANCELLED','ADMIN_CANCELLED')) NOT VALID;
-- NOT VALID preserves legacy rows (for example 'Requested'). New writes are checked.
ALTER TABLE invoices DROP CONSTRAINT IF EXISTS ck_invoice_status;
ALTER TABLE invoices ADD CONSTRAINT ck_invoice_status CHECK
    (status IN ('PENDING','PAID','SETTLED','REFUNDED')) NOT VALID;

CREATE TABLE IF NOT EXISTS ride_payments (
    ride_id INTEGER PRIMARY KEY REFERENCES ride_details(ride_id),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    business_paise BIGINT NOT NULL CHECK (business_paise >= 0),
    rider_paise BIGINT NOT NULL CHECK (rider_paise > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    receipt VARCHAR(40) NOT NULL UNIQUE,
    order_id VARCHAR(64) UNIQUE,
    payment_id VARCHAR(64) UNIQUE,
    status VARCHAR(32) NOT NULL DEFAULT 'CREATING'
        CHECK (status IN ('CREATING','ORDER_CREATED','CAPTURED','REFUND_REQUIRED','REFUNDED')),
    transfer_status VARCHAR(32) NOT NULL DEFAULT 'NOT_ELIGIBLE'
        CHECK (transfer_status IN ('NOT_ELIGIBLE','WAITING_ROUTE','READY','SUBMITTING','RECONCILE','PROCESSED','SETTLED','FAILED')),
    transfer_id VARCHAR(64) UNIQUE,
    transfer_account_id VARCHAR(64),
    last_error VARCHAR(256),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (business_paise + rider_paise = amount_paise)
);

-- Populate only through a trusted operations connection after Razorpay onboarding.
-- Application ADMIN is a paying customer, not a privileged finance operator.
CREATE TABLE IF NOT EXISTS rider_route_accounts (
    rider_id BIGINT PRIMARY KEY REFERENCES rider_details(id),
    account_id VARCHAR(64) NOT NULL UNIQUE CHECK (account_id LIKE 'acc_%'),
    approved BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS razorpay_webhook_events (
    event_id VARCHAR(256) PRIMARY KEY,
    event_type VARCHAR(80) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ride_payments_transfer ON ride_payments(transfer_status);
ALTER TABLE ride_details ADD COLUMN IF NOT EXISTS booking_key VARCHAR(100);
ALTER TABLE ride_details ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
CREATE UNIQUE INDEX IF NOT EXISTS uq_ride_booking_key ON ride_details(admin_id, booking_key) WHERE booking_key IS NOT NULL;
CREATE TABLE IF NOT EXISTS request_limits (
    purpose VARCHAR(32) NOT NULL, identity VARCHAR(255) NOT NULL,
    window_start TIMESTAMPTZ NOT NULL, attempts INTEGER NOT NULL,
    PRIMARY KEY(purpose,identity)
);
CREATE INDEX IF NOT EXISTS idx_request_limits_window ON request_limits(window_start);
CREATE TABLE IF NOT EXISTS checkout_sessions (
    token_hash VARCHAR(64) PRIMARY KEY, ride_id INTEGER NOT NULL REFERENCES ride_details(ride_id),
    username VARCHAR(255) NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_checkout_sessions_expiry ON checkout_sessions(expires_at);
